import { expect } from "bun:test";

import { Task } from "@sshkeda/task";

import { ruleTestWith } from "../shared/rule-test.ts";

const ruleTest = ruleTestWith(({ reported, expected }) => {
  expect(reported).toMatchObject(expected);
});

const instant = (usage: string) => ({
  message: `${usage} retries at once, with no wait between attempts`,
});

export const instantRetriesAreRejected = Task.make(
  "no-instant-retries reports an Effect or Stream retry whose policy is no schedule or only a bare Schedule.recurs(n), and leaves timed or mapped schedules, unknown policies and repeats alone",
  ruleTest("no-instant-retries", {
    valid: [
      'import { Effect, Schedule } from "effect"; Effect.retry(work, { times: 3, schedule: Schedule.spaced("1 second") });',
      'import { Effect, Schedule } from "effect"; work.pipe(Effect.retry(Schedule.exponential("10 millis")));',
      'import { Effect, Schedule } from "effect"; Effect.retry(work, Schedule.exponential("10 millis"));',
      'import { Effect, Schedule } from "effect"; Effect.retry(work, { times: 3, schedule: Schedule.exponential("10 millis") });',
      'import { Effect, Schedule } from "effect"; Effect.retry(work, Schedule.jittered(Schedule.exponential("10 millis")));',
      'import { Effect, Schedule } from "effect"; work.pipe(Effect.retry(Schedule.exponential("10 millis").pipe(Schedule.jittered)));',
      'import { Effect, Schedule } from "effect"; Effect.retry(work, Schedule.recurs(3).pipe(Schedule.addDelay(() => "1 second")));',
      'import { Effect, Schedule } from "effect"; Effect.retry(work, Schedule.spaced("0 millis"));',
      'import { Effect } from "effect"; Effect.retry(work, policy);',
      'import { Effect } from "effect"; Effect.retry(work, { ...policy, times: 3 });',
      'import { Effect } from "effect"; Effect.retry(work, { [option]: 3 });',
      'import { Effect, Schedule } from "effect"; Effect.retry(work, Schedule.recurs(3).pipe(Schedule.map(() => Effect.sleep("1 second"))));',
      'import { Effect } from "effect"; Effect.retry(work, { schedule, times: 3 });',
      'import { Effect, Queue } from "effect"; Effect.retry(Effect.fail("transient"), { while: () => Queue.take(retrySignals) });',
      'import { Effect, Queue } from "effect"; work.pipe(Effect.retry({ until: () => { return Queue.take(retrySignals); } }));',
      'import { Effect, Queue, Schedule } from "effect"; Effect.retry(work, { while: () => Queue.take(retrySignals), schedule: Schedule.recurs(3) });',
      'import { Effect, Queue } from "effect"; Effect.retryOrElse(work, { until: () => Queue.take(retrySignals) }, recover);',
      'import { Effect, Queue } from "effect"; const waitForRetry = () => Queue.take(retrySignals); Effect.retry(work, { while: waitForRetry });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { until: waitForRetry }); function waitForRetry() { return Queue.take(retrySignals); }',
      'import { Effect } from "effect"; Effect.retry(work, { while: () => Effect.succeed(true).pipe(Effect.delay("1 second")) });',
      'import { Effect } from "effect"; const retrySignal = Effect.succeed(true); Effect.retry(work, { until: () => retrySignal });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => ready ? true : Queue.take(retrySignals) });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => { recordAttempt(); return Queue.take(retrySignals); } });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => { const signal = Queue.take(retrySignals); return signal; } });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => { if (ready) { return true; } return Queue.take(retrySignals); } });',
      'import { Effect, Queue } from "effect"; function waitForRetry() { recordAttempt(); return Queue.take(retrySignals); } Effect.retry(work, { while: () => waitForRetry() });',
      'import { Effect } from "effect"; Effect.retry(work, { until: () => { recordAttempt(); return waitForRetry(); } });',
      'import { Effect } from "effect"; declare const retrySignal: Effect.Effect<boolean>; Effect.retry(work, { while: () => { recordAttempt(); return retrySignal; } });',
      'import { Effect, Queue } from "effect"; let retrySignal; Effect.retry(work, { while: () => { recordAttempt(); return retrySignal = Queue.take(retrySignals); } });',
      'import { Effect, Queue } from "effect"; const signals = { includes: () => Queue.take(retrySignals) }; Effect.retry(work, { while: () => signals.includes() });',
      'import { Effect, Queue } from "effect"; const Boolean = () => Queue.take(retrySignals); Effect.retry(work, { while: () => Boolean() });',
      'import { Effect, Queue } from "effect"; const Array = { isArray: () => Queue.take(retrySignals) }; Effect.retry(work, { while: () => Array.isArray() });',
      'import { Effect, Queue } from "effect"; class Set { has() { return Queue.take(retrySignals); } } Effect.retry(work, { while: () => new Set().has() });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => { switch (state) { case "waiting": return Queue.take(retrySignals); default: return true; } } });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => { try { recordAttempt(); return true; } catch { return Queue.take(retrySignals); } } });',
      'import { Effect, Queue } from "effect"; Effect.retry(work, { while: () => { for (const signal of retrySignals) { return Queue.take(signal); } return false; } });',
      'import { Effect } from "effect"; function waitForRetry() { return waitForRetry(); } Effect.retry(work, { while: () => waitForRetry() });',
      'import { Effect } from "effect"; work.pipe(Effect.retry(($) => $.recurs(3)));',
      'import { Effect, Schedule } from "effect"; work.pipe(Effect.repeat({ times: 3 }), Effect.repeat(Schedule.recurs(3)));',
      'import { Effect } from "other"; Effect.retry(work, { times: 3 });',
      "const Effect = { retry: () => 1 }; Effect.retry(work, { times: 3 });",
      'import { Stream, Schedule } from "effect"; stream.pipe(Stream.retry(Schedule.spaced("1 second")));',
      'import { Stream, Schedule } from "effect"; stream.pipe(Stream.retry(Schedule.exponential("10 millis")));',
      'import { Stream, Schedule } from "effect"; stream.pipe(Stream.retry(Schedule.exponential("10 millis").pipe(Schedule.jittered)));',
    ],
    invalid: [
      ...[
        'import { Effect } from "effect"; Effect.retry(work, { times: 3 });',
        'import { Effect } from "effect"; work.pipe(Effect.retry({ times: 3 }));',
        'import { Effect } from "effect"; work.pipe(Effect.retry({ while: isLocked, times: 3 }));',
        'import { Effect } from "effect"; work.pipe(Effect.retry({ until: isDone }));',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => true });',
        'import { Effect } from "effect"; Effect.retry(work, { until: () => false });',
        'import { Effect } from "effect"; Effect.retry(work, { while: (error) => error.retryable === true });',
        'import { Effect } from "effect"; const shouldRetry = () => true; Effect.retry(work, { while: shouldRetry });',
        'import { Effect } from "effect"; const shouldRetry = () => true; Effect.retry(work, { while: () => shouldRetry() });',
        'import { Effect } from "effect"; const shouldRetry = (): boolean => remaining > 0; Effect.retry(work, { while: () => shouldRetry() });',
        'import { Effect } from "effect"; Effect.retry(work, { until: isDone }); function isDone() { return false; }',
        'import { Effect } from "effect"; Effect.retry(work, { while: (): boolean => shouldRetry() });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => Boolean(remaining) });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => Effect.isEffect(work) });',
        'import { Effect } from "effect"; Effect.retry(Effect.fail("transient"), { times: 3, while: () => { const retryable = true; return retryable; } });',
        'import { Effect } from "effect"; function shouldRetry() { recordAttempt(); return true; } Effect.retry(work, { while: () => shouldRetry() });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => { if (ready) { return true; } else { return false; } } });',
        'import { Effect } from "effect"; Effect.retry(work, { until: () => { switch (state) { case "ready": return true; default: return false; } } });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => { try { return true; } catch { return false; } finally { recordAttempt(); } } });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => { for (const attempt of attempts) { if (attempt) { return true; } } return false; } });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => { function wait() { return Effect.sleep("1 second"); } return true; } });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => [true].includes(true) });',
        'import { Effect } from "effect"; const retryable = [true]; Effect.retry(work, { while: () => retryable.some(Boolean) });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => "transient".startsWith("trans") });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => /transient/u.test("transient") });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => new Set([true]).has(true) });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => Array.isArray(values) });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => Number.isFinite(remaining) });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => Object.is(remaining, 1) });',
        'import { Effect } from "effect"; let retryable: boolean = true; Effect.retry(work, { while: () => { recordAttempt(); return retryable; } });',
        'import { Effect } from "effect"; Effect.retry(work, { while: (): true | false => { recordAttempt(); return shouldRetry(); } });',
        'import { Effect } from "effect"; Effect.retry(work, { while: () => (Effect.sleep("1 second"), true) });',
        'import { Effect, Schedule } from "effect"; Effect.retry(work, { until: () => false, schedule: Schedule.recurs(3) });',
        'import { Effect } from "effect"; work.pipe(Effect.retry({ "times": 3 } as const));',
        'import { Effect, Schedule } from "effect"; Effect.retry(work, Schedule.recurs(3));',
        'import { Effect, Schedule } from "effect"; work.pipe(Effect.retry({ schedule: Schedule.recurs(3) }));',
        'import { Effect } from "effect"; work.pipe(Effect.retry({ times: 3, schedule: undefined }));',
        'import { Effect } from "effect"; work.pipe(Effect.retry({ ["times"]: 3 }));',
        'import { retry } from "effect/Effect"; work.pipe(retry({ times: 3 }));',
        'import * as Library from "effect"; work.pipe(Library.Effect.retry({ times: 3 }));',
      ].map((code) => ({ code, errors: [instant("Effect.retry")] })),
      ...[
        'import { Effect } from "effect"; Effect.retryOrElse(work, { times: 3 }, recover);',
        'import { Effect } from "effect"; work.pipe(Effect.retryOrElse({ times: 3 }, recover));',
      ].map((code) => ({ code, errors: [instant("Effect.retryOrElse")] })),
      ...[
        'import { Schedule, Stream } from "effect"; stream.pipe(Stream.retry(Schedule.recurs(3)));',
        'import { Schedule, Stream } from "effect"; Stream.retry(stream, Schedule.recurs(3));',
      ].map((code) => ({ code, errors: [instant("Stream.retry")] })),
    ],
  }),
);
